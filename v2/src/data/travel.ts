export const transitMin = (from: string, to: string): number => travelMatrix[from]?.[to] ?? 0

/** Total transit minutes along an ordered list of stops. One stop or none is zero travel. */
export const routeMin = (stops: string[]): number =>
  stops.reduce((sum, id, i) => (i === 0 ? 0 : sum + transitMin(stops[i - 1] ?? id, id)), 0)
