/**
 * Builds concise-slides.html from slides.html.
 *
 * The full deck is the submission: every scored band gets its own slide, and the
 * two ideation canvases are the 8% Visual Diagrams evidence, so nothing there can
 * be cut without losing marks. A deck read at a table is not a deck presented at a
 * podium, though, and nineteen slides is too many to speak to. This is the podium
 * cut: twelve slides that carry the argument end to end.
 *
 * Seven sections come out. Each one's claim survives somewhere else in the deck,
 * or is written down in the README, which is where the rubric says ideation and
 * mentor evidence is actually read:
 *
 *   07 the user flow canvas   - the mindmap on 06 already carries the diagram band
 *   08 thirteen directions    - README 2.1 is the dropped table, dated
 *   09 two we built, then killed
 *   10 the mentor session     - README records it; the deck cannot fit a transcript
 *   12 the capability matrix  - 11 already says what only Perch does
 *   17 the build plan         - 16 states the stack and what the build adds
 *   18 the non-claims         - README carries them in full
 *
 * Nothing is rewritten here. The slides are the same objects, in the same order,
 * renumbered so the footers do not lie. Regenerate after any edit to slides.html:
 *
 *     node build-concise.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const src = readFileSync(join(here, 'slides.html'), 'utf8')

/** Zero-based indices of the sections the podium cut keeps, in order. */
const KEEP = [0, 1, 2, 3, 4, 5, 10, 12, 13, 14, 15, 18]

const OPEN = '<section class="slide'
const first = src.indexOf(OPEN)
const lastClose = src.lastIndexOf('</section>') + '</section>'.length
if (first < 0) throw new Error('no slides found')

const head = src.slice(0, first)
const tail = src.slice(lastClose)

// Split on the section openings, keeping each section whole along with the
// comment block that introduces it, which is where the authoring notes live.
const body = src.slice(first, lastClose)
const parts = []
let cursor = 0
while (cursor < body.length) {
  const next = body.indexOf(OPEN, cursor + 1)
  const end = next === -1 ? body.length : next
  parts.push(body.slice(cursor, end))
  cursor = end
}
if (parts.length !== 19) throw new Error(`expected 19 sections, found ${parts.length}`)

const total = KEEP.length
const kept = KEEP.map((i, n) => {
  const seq = String(n + 1).padStart(2, '0')
  return parts[i]
    .replace(/<span class="run">\d\d \/ \d+<\/span>/, `<span class="run">${seq} / ${total}</span>`)
    .replace(/<span class="num">\d\d \/ \d+<\/span>/, `<span class="num">${seq} / ${total}</span>`)
})

const note = `<!-- Generated by build-concise.mjs from slides.html. Do not edit by hand:
     edit slides.html and regenerate, or the two decks drift apart. -->\n`

const out = head
  .replace(/<title>[^<]*<\/title>/, '<title>Perch, the short cut</title>')
  .replace('<body>\n', '<body>\n' + note) +
  kept.join('') +
  tail

writeFileSync(join(here, 'concise-slides.html'), out)
console.log(`concise-slides.html: ${total} slides from ${parts.length}, ${(out.length / 1024).toFixed(0)} KB`)
